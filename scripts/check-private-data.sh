#!/usr/bin/env bash
# Fail if the repository contains anything that looks like real data. Run it before every push; CI runs it too.
# It checks tracked files (git ls-files), so it also protects against a forced `git add -f`.
#
# What it looks for:
#   1. file types that carry recordings, results or secrets
#   2. images outside docs/images (documentation images must be synthetic, see docs/privacy.md)
#   3. an ntfy topic name in the form this project generates (lpr-<24 lowercase letters or digits>)
#   4. plate-like text in the OCR results format ("DEMO..." plates are allowed, they are made up)
set -u
cd "$(git rev-parse --show-toplevel)"
bad=0
fail() { echo "BLOCKED: $1"; bad=1; }

while IFS= read -r f; do
  case "$f" in
    *.dav|*.idx|*index.csv|*second_pass.csv|*labels.jsonl|*alerts.jsonl|*ntfy_topic|*watchlist.csv|*/config.toml|config.toml)
      fail "$f (recordings, results, labels or per-user state must never be committed)";;
  esac
  case "$f" in
    docs/images/*.png) ;;
    *.png|*.jpg|*.jpeg|*.gif|*.bmp|*.tif|*.tiff|*.webp|*.mp4|*.mov)
      fail "$f (images are only allowed under docs/images/, and must be synthetic)";;
  esac
done < <(git ls-files)

# an ntfy topic generated by `lpr watch --init`
if git grep -nIE 'lpr-[a-z0-9]{24}' -- . ':!scripts/check-private-data.sh' ':!tests' >/dev/null 2>&1; then
  git grep -nIE 'lpr-[a-z0-9]{24}' -- . ':!scripts/check-private-data.sh' ':!tests' | sed 's/^/BLOCKED: possible ntfy topic: /'
  bad=1
fi

# result-format filenames such as 2026-01-01_03.15.11-03.15.30-ABC1234_0.99.png containing a non-demo plate
if git grep -nIE '[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}\.[0-9]{2}\.[0-9]{2}-[0-9]{2}\.[0-9]{2}\.[0-9]{2}-[A-Z0-9]{2,8}_[01]\.[0-9]{2}\.png' -- . ':!scripts/check-private-data.sh' ':!tests' | grep -v 'DEMO\|DEM0\|DEHO' | grep -q .; then
  git grep -nIE '[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}\.[0-9]{2}\.[0-9]{2}-[0-9]{2}\.[0-9]{2}\.[0-9]{2}-[A-Z0-9]{2,8}_[01]\.[0-9]{2}\.png' -- . ':!scripts/check-private-data.sh' ':!tests' | grep -v 'DEMO\|DEM0\|DEHO' | sed 's/^/BLOCKED: result file name with a real-looking plate: /'
  bad=1
fi

if [ "$bad" -eq 0 ]; then echo "ok: no private data patterns found"; fi
exit "$bad"
